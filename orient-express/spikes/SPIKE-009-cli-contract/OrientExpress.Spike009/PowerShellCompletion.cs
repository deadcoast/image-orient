using System.CommandLine;
using System.Text;

namespace OrientExpress.Spike009;

/// <summary>
/// Deterministic PowerShell completion generated from the same command model
/// the parser uses (DOC-CLI: completion comes from the command model, not a
/// hand-maintained list).
/// </summary>
public static class PowerShellCompletion
{
    public static string Generate(RootCommand root)
    {
        ArgumentNullException.ThrowIfNull(root);

        var builder = new StringBuilder();
        builder.Append("# Generated by ").Append(CliHost.ExecutableName)
            .Append(" completion powershell — contract ").Append(CliHost.ContractVersion).Append('\n');
        builder.Append("Register-ArgumentCompleter -Native -CommandName ")
            .Append(CliHost.ExecutableName).Append(" -ScriptBlock {\n");
        builder.Append("    param($wordToComplete, $commandAst, $cursorPosition)\n");
        builder.Append("    $completions = @(\n");
        foreach (var name in CompletionTokens(root))
        {
            builder.Append("        '").Append(name).Append("'\n");
        }

        builder.Append("    )\n");
        builder.Append("    $completions -like \"$wordToComplete*\" | ForEach-Object {\n");
        builder.Append("        [System.Management.Automation.CompletionResult]::new($_, $_, 'ParameterValue', $_)\n");
        builder.Append("    }\n");
        builder.Append("}\n");
        return builder.ToString();
    }

    private static SortedSet<string> CompletionTokens(Command root)
    {
        var tokens = new SortedSet<string>(StringComparer.Ordinal);
        Collect(root, tokens, isRoot: true);
        return tokens;
    }

    private static void Collect(Command command, SortedSet<string> tokens, bool isRoot)
    {
        if (!isRoot)
        {
            tokens.Add(command.Name);
        }

        foreach (var option in command.Options)
        {
            tokens.Add(option.Name);
        }

        foreach (var child in command.Subcommands)
        {
            Collect(child, tokens, isRoot: false);
        }
    }
}
